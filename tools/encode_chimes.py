#!/usr/bin/env python3
"""Encode cleaned Harman chime WAV files into 22.05 kHz 4-bit IMA ADPCM C++ arrays.

Usage:
  python3 tools/encode_chimes.py
"""
import math
import os
import struct
import subprocess
import tempfile
import wave

TARGET_SR = 22050

IMA_INDEX_TABLE = [
    -1, -1, -1, -1, 2, 4, 6, 8,
    -1, -1, -1, -1, 2, 4, 6, 8,
]

IMA_STEP_TABLE = [
    7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31,
    34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97, 107, 118, 130, 143,
    157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544,
    598, 658, 724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878,
    2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871, 5358, 5894,
    6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818,
    18500, 20350, 22385, 24623, 27086, 29794, 32767,
]


def resample_to_mono_pcm16(wav_path: str, target_sr: int) -> list[int]:
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tf:
        tmp_path = tf.name
    try:
        subprocess.run(
            [
                "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
                "-i", wav_path,
                "-ar", str(target_sr), "-ac", "1",
                "-c:a", "pcm_s16le",
                tmp_path,
            ],
            check=True,
        )
        with wave.open(tmp_path, "rb") as w:
            n = w.getnframes()
            return list(struct.unpack(f"<{n}h", w.readframes(n)))
    finally:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)


def encode_ima_adpcm(samples: list[int]) -> tuple[bytes, list[int]]:
    """Standard 4-bit IMA ADPCM encoder (low nibble first, initial predictor=0, index=0)."""
    predictor = 0
    index = 0
    nibbles = []
    decoded = []

    for s in samples:
        step = IMA_STEP_TABLE[index]
        diff = s - predictor
        code = 0
        if diff < 0:
            code = 8
            diff = -diff

        vpdiff = step >> 3
        if diff >= step:
            code |= 4
            diff -= step
            vpdiff += step
        step >>= 1
        if diff >= step:
            code |= 2
            diff -= step
            vpdiff += step
        step >>= 1
        if diff >= step:
            code |= 1
            vpdiff += step

        if code & 8:
            predictor -= vpdiff
        else:
            predictor += vpdiff

        if predictor > 32767:
            predictor = 32767
        elif predictor < -32768:
            predictor = -32768

        index += IMA_INDEX_TABLE[code]
        if index < 0:
            index = 0
        elif index > 88:
            index = 88

        nibbles.append(code & 0x0F)
        decoded.append(predictor)

    # Pack two 4-bit nibbles per byte (low nibble = even sample, high nibble = odd sample)
    out = bytearray()
    for i in range(0, len(nibbles), 2):
        lo = nibbles[i]
        hi = nibbles[i + 1] if (i + 1) < len(nibbles) else 0
        out.append((hi << 4) | lo)

    return bytes(out), decoded


def format_c_array(name: str, data: bytes) -> str:
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        hex_vals = ", ".join(f"0x{b:02X}" for b in chunk)
        lines.append(f"  {hex_vals},")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    clips = [
        ("POWER_ON",  "kPowerOnAdpcm",  "chime_recodings/cleaned/Poweron_clean.wav"),
        ("POWER_OFF", "kPowerOffAdpcm", "chime_recodings/cleaned/Poweroff_clean.wav"),
        ("PAIRING",   "kPairingAdpcm",  "chime_recodings/cleaned/Pairingmode_clean.wav"),
    ]

    encoded = []
    total_bytes = 0
    for clip_name, arr_name, wav_path in clips:
        pcm = resample_to_mono_pcm16(wav_path, TARGET_SR)
        adpcm, dec = encode_ima_adpcm(pcm)
        sig_p = sum(x * x for x in pcm) + 1e-18
        err_p = sum((a - b) ** 2 for a, b in zip(pcm, dec)) + 1e-18
        snr_db = 10.0 * math.log10(sig_p / err_p)
        total_bytes += len(adpcm)
        print(
            f"{clip_name:10s}: {len(pcm)} samples ({len(pcm)/TARGET_SR:.3f}s @ {TARGET_SR} Hz) -> "
            f"{len(adpcm):6d} bytes ({len(adpcm)/1024:.2f} KB), SNR = {snr_db:.2f} dB"
        )
        encoded.append((clip_name, arr_name, adpcm, len(pcm)))

    print(f"TOTAL FLASH DATA: {total_bytes} bytes ({total_bytes/1024:.2f} KB)")

    header_src = """#pragma once
#include <stddef.h>
#include <stdint.h>

// Auto-generated by tools/encode_chimes.py — 22.05 kHz 4-bit IMA ADPCM Harman chimes
namespace ChimeData {

constexpr uint32_t SAMPLE_RATE_HZ = 22050;

struct AdpcmClip {
  const uint8_t *data;
  size_t         byteLen;
  uint32_t       sampleCount;
};

extern const AdpcmClip POWER_ON;
extern const AdpcmClip POWER_OFF;
extern const AdpcmClip PAIRING;

} // namespace ChimeData
"""
    with open("include/chime_data.h", "w", encoding="utf-8") as f:
        f.write(header_src)

    cpp_parts = [
        '#include "chime_data.h"',
        "",
        "// Auto-generated by tools/encode_chimes.py — 22.05 kHz 4-bit IMA ADPCM Harman chimes",
        "namespace ChimeData {",
        "",
    ]
    for _, arr_name, adpcm, _ in encoded:
        cpp_parts.append(format_c_array(arr_name, adpcm))
        cpp_parts.append("")
    for clip_name, arr_name, adpcm, sample_count in encoded:
        cpp_parts.append(
            f"const AdpcmClip {clip_name} = {{ {arr_name}, sizeof({arr_name}), {sample_count}U }};"
        )
    cpp_parts.append("")
    cpp_parts.append("} // namespace ChimeData")
    cpp_parts.append("")

    with open("src/chime_data.cpp", "w", encoding="utf-8") as f:
        f.write("\n".join(cpp_parts))


if __name__ == "__main__":
    main()
