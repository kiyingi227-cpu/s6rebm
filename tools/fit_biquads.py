#!/usr/bin/env python3
"""
Constrained Parametric Biquad Fitter & C++ Header Generator (Part C5 of brief).

Fits a cascade of N peaking biquads (optional low/high shelf) to H_req(f) using
scipy.optimize.least_squares with strict bounds:
  - f0 in [60 Hz, 16000 Hz] (never boosts below the mandatory 48 Hz HPF)
  - Q  in [0.5, 6.0]
  - gain in [-12.0, +6.0] dB

Outputs include/eq_coeffs.h with:
  - Pre-gain (headroom guarantee so 0 dBFS never clips)
  - Precomputed 48 kHz normalized TDF-II coefficients (a0 = 1, denom 1 + a1*z^-1 + a2*z^-2)
  - Parametric specs (f0, Q, gainDb) so the ESP32 can also recompute cleanly at 44.1 kHz
  - Extracted Studio 9 dynamic bass DRC parameters
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import List, Tuple

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.optimize import least_squares


def peaking_coeffs(f0: float, fs: float, Q: float, gain_db: float) -> Tuple[float, float, float, float, float]:
    """Audio EQ Cookbook peaking filter (Appendix A), normalized so a0 = 1."""
    A = 10.0 ** (gain_db / 40.0)
    w0 = 2.0 * np.pi * f0 / fs
    c = np.cos(w0)
    s = np.sin(w0)
    alpha = s / (2.0 * Q)
    a0 = 1.0 + alpha / A
    b0 = (1.0 + alpha * A) / a0
    b1 = (-2.0 * c) / a0
    b2 = (1.0 - alpha * A) / a0
    a1 = (-2.0 * c) / a0
    a2 = (1.0 - alpha / A) / a0
    return float(b0), float(b1), float(b2), float(a1), float(a2)


def cascade_mag_db(freqs: np.ndarray, fs: float, params: np.ndarray) -> np.ndarray:
    """Evaluate cascade magnitude in dB for params = [log_f0_0, Q_0, G_0, ...]."""
    w = 2.0 * np.pi * freqs / fs
    z1 = np.exp(-1j * w)
    z2 = z1 * z1
    H = np.ones_like(freqs, dtype=np.complex128)
    n_sec = len(params) // 3
    for k in range(n_sec):
        f0 = float(np.exp(params[3 * k]))
        Q = float(params[3 * k + 1])
        G = float(params[3 * k + 2])
        b0, b1, b2, a1, a2 = peaking_coeffs(f0, fs, Q, G)
        H *= (b0 + b1 * z1 + b2 * z2) / (1.0 + a1 * z1 + a2 * z2)
    return 20.0 * np.log10(np.maximum(np.abs(H), 1e-12))


def max_pole_radius(a1: float, a2: float) -> float:
    roots = np.roots([1.0, a1, a2])
    return float(np.max(np.abs(roots)))


def tdf2_process(x: np.ndarray, sections: List[Tuple[float, float, float, float, float]], pre_gain: float) -> np.ndarray:
    """Exact Direct Form II Transposed reference matching C++ Biquad::process()."""
    y = x.astype(np.float32) * np.float32(pre_gain)
    for b0, b1, b2, a1, a2 in sections:
        z1 = np.float32(0.0)
        z2 = np.float32(0.0)
        out = np.empty_like(y)
        b0f, b1f, b2f, a1f, a2f = map(np.float32, (b0, b1, b2, a1, a2))
        for i in range(len(y)):
            xi = y[i]
            yi = b0f * xi + z1
            z1 = b1f * xi - a1f * yi + z2
            z2 = b2f * xi - a2f * yi
            out[i] = yi
        y = out
    return y


def write_cpp_header(path: Path, fs: int, pre_gain_db: float, sections_param: List[dict], drc: dict) -> None:
    pre_gain_lin = 10.0 ** (pre_gain_db / 20.0)
    lines = [
        "#pragma once",
        "#include <stdint.h>",
        "",
        "// Auto-generated by tools/fit_biquads.py from acoustic SysID measurements.",
        "// Denominator sign convention: H(z) = (b0 + b1*z^-1 + b2*z^-2) / (1 + a1*z^-1 + a2*z^-2)",
        "// Direct Form II Transposed: y = b0*x + z1; z1 = b1*x - a1*y + z2; z2 = b2*x - a2*y;",
        "",
        "namespace SysidEq {",
        "",
        "struct EqSection {",
        "  float f0;",
        "  float Q;",
        "  float gainDb;",
        "  float b0, b1, b2, a1, a2; // Precomputed for EQ_REF_SAMPLE_RATE",
        "};",
        "",
        "struct DrcConfig {",
        "  bool  enabled;",
        "  float sidechainHz;",
        "  float thresholdDbfs;",
        "  float ratio;",
        "  float kneeDb;",
        "  float attackMs;",
        "  float releaseMs;",
        "};",
        "",
        "constexpr bool     EQ_HAS_FIT         = true;",
        f"constexpr uint32_t EQ_REF_SAMPLE_RATE = {fs};",
        f"constexpr float    EQ_PRE_GAIN_DB     = {pre_gain_db:.4f}f;",
        f"constexpr float    EQ_PRE_GAIN_LIN    = {pre_gain_lin:.8f}f;",
        f"constexpr uint8_t  EQ_NUM_SECTIONS    = {len(sections_param)};",
        "",
        "constexpr EqSection EQ_SECTIONS[EQ_NUM_SECTIONS] = {",
    ]
    for s in sections_param:
        lines.append(
            f"  {{{s['f0']:.2f}f, {s['Q']:.4f}f, {s['gain_db']:.4f}f, "
            f"{s['b0']:.9f}f, {s['b1']:.9f}f, {s['b2']:.9f}f, {s['a1']:.9f}f, {s['a2']:.9f}f}},"
        )
    lines.extend([
        "};",
        "",
        "constexpr DrcConfig DRC_CONFIG = {",
        "  true,",
        f"  {drc.get('sidechain_hz', 120.0):.2f}f,",
        f"  {drc.get('threshold_esp32_dbfs', -12.0):.3f}f,",
        f"  {drc.get('ratio', 4.0):.3f}f,",
        f"  {drc.get('knee_db', 6.0):.3f}f,",
        f"  {drc.get('attack_tau_ms_mean', 15.0):.2f}f,",
        f"  {drc.get('release_tau_ms_mean', 250.0):.2f}f,",
        "};",
        "",
        "} // namespace SysidEq",
        "",
    ])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Fit bounded parametric biquads to H_req and write eq_coeffs.h.")
    parser.add_argument("--results", type=Path, required=True, help="Path to sysid_results.json")
    parser.add_argument("--sections", type=int, default=8, help="Number of peaking biquad sections (6..10)")
    parser.add_argument("--restarts", type=int, default=6, help="Number of random restarts")
    parser.add_argument("--f-min", type=float, default=60.0, help="Lower fit bound in Hz (keep >= 60 Hz above 48 Hz HPF)")
    parser.add_argument("--f-max", type=float, default=12000.0, help="Upper fit bound in Hz")
    parser.add_argument("--q-max", type=float, default=4.5, help="Upper Q bound (default 4.5 for smooth musical phase)")
    parser.add_argument("--out-header", type=Path, default=Path("include/eq_coeffs.h"), help="Output C++ header path")
    parser.add_argument("--out-plot", type=Path, default=Path("tools/results/plot_eq_fit.png"), help="Output fit plot")
    args = parser.parse_args()

    with open(args.results, "r", encoding="utf-8") as f:
        res = json.load(f)

    fs = int(res["sample_rate"])
    freqs = np.array(res["grid_freqs_hz"], dtype=np.float64)
    target_db = np.array(res["h_req_db"], dtype=np.float64)
    snr_valid = np.array(res["snr_valid"], dtype=bool)

    mask = snr_valid & (freqs >= args.f_min) & (freqs <= args.f_max)
    f_fit = freqs[mask]
    y_fit = np.clip(target_db[mask], -12.0, 6.0)

    # Weight 100 Hz .. 8 kHz highest per Part C5
    weights = np.ones_like(f_fit)
    weights[(f_fit >= 100.0) & (f_fit <= 8000.0)] = 2.0

    n = args.sections
    lb = np.tile([np.log(args.f_min), 0.5, -12.0], n)
    ub = np.tile([np.log(args.f_max), args.q_max, 6.0], n)

    def residuals(p: np.ndarray) -> np.ndarray:
        pred = cascade_mag_db(f_fit, fs, p)
        err = weights * (pred - y_fit)
        # Small boost penalty to prevent optimizer from piling up unnecessary gain
        boosts = np.maximum(p[2::3], 0.0)
        return np.concatenate([err, 0.15 * boosts])

    rng = np.random.default_rng(42)
    best_sol = None

    for r in range(args.restarts):
        if r == 0:
            # Deterministic log-spaced seed initialized from local target deviations
            seed_f = np.geomspace(args.f_min * 1.2, args.f_max * 0.85, n)
            p0 = np.zeros(3 * n)
            for k in range(n):
                p0[3 * k] = np.log(seed_f[k])
                p0[3 * k + 1] = 1.4
                p0[3 * k + 2] = float(np.clip(np.interp(seed_f[k], f_fit, y_fit) * 0.5, -10.0, 5.0))
        else:
            p0 = np.zeros(3 * n)
            seed_f = np.sort(np.exp(rng.uniform(np.log(args.f_min * 1.1), np.log(args.f_max * 0.9), n)))
            for k in range(n):
                p0[3 * k] = np.log(seed_f[k])
                p0[3 * k + 1] = float(rng.uniform(0.7, 3.0))
                p0[3 * k + 2] = float(rng.uniform(-4.0, 3.0))

        sol = least_squares(residuals, p0, bounds=(lb, ub), max_nfev=2500)
        if best_sol is None or sol.cost < best_sol.cost:
            best_sol = sol

    p_best = best_sol.x
    # Sort sections by center frequency for readability
    order = np.argsort(p_best[0::3])
    sections_param = []
    sections_coeffs = []
    max_pole = 0.0

    for idx in order:
        f0 = float(np.exp(p_best[3 * idx]))
        Q = float(p_best[3 * idx + 1])
        G = float(p_best[3 * idx + 2])
        b0, b1, b2, a1, a2 = peaking_coeffs(f0, fs, Q, G)
        pr = max_pole_radius(a1, a2)
        max_pole = max(max_pole, pr)
        sections_param.append({
            "f0": f0, "Q": Q, "gain_db": G,
            "b0": b0, "b1": b1, "b2": b2, "a1": a1, "a2": a2,
            "pole_radius": pr,
        })
        sections_coeffs.append((b0, b1, b2, a1, a2))

    # Headroom calculation over full 20 Hz .. 20 kHz band
    fit_full_db = cascade_mag_db(freqs, fs, p_best)
    max_boost_db = max(0.0, float(np.max(fit_full_db)))
    pre_gain_db = -(max_boost_db + 0.5)  # extra 0.5 dB safety margin

    # Self-check stability & TDF-II impulse response
    assert max_pole < 0.9999, f"Unstable pole detected: {max_pole}"
    imp = np.zeros(1024, dtype=np.float32)
    imp[0] = 1.0
    _ = tdf2_process(imp, sections_coeffs, 10.0 ** (pre_gain_db / 20.0))

    write_cpp_header(args.out_header, fs, pre_gain_db, sections_param, res.get("drc", {}))

    # Per-band residual summary
    eval_100_10k = mask & (freqs >= 100.0) & (freqs <= 10000.0)
    resid_100_10k = fit_full_db[eval_100_10k] - target_db[eval_100_10k]
    rms_err = float(np.sqrt(np.mean(resid_100_10k ** 2)))
    max_err = float(np.max(np.abs(resid_100_10k)))

    args.out_plot.parent.mkdir(parents=True, exist_ok=True)
    plt.figure(figsize=(10, 6))
    plt.semilogx(freqs, target_db, label="Target H_req (T9 / P6)", alpha=0.8)
    plt.semilogx(freqs, fit_full_db, label=f"Fitted {n}-Biquad Cascade", linewidth=2)
    plt.semilogx(freqs, fit_full_db - target_db, "--", label="Residual (Fit - Target)")
    plt.xlim(20, 20000); plt.ylim(-16, 12); plt.grid(True, which="both", alpha=0.3)
    plt.xlabel("Frequency (Hz)"); plt.ylabel("Gain (dB)")
    plt.title(f"EQ Fit: RMS(100Hz-10kHz)={rms_err:.2f} dB, Max={max_err:.2f} dB, Pre-gain={pre_gain_db:.2f} dB")
    plt.legend(); plt.tight_layout()
    plt.savefig(args.out_plot, dpi=150); plt.close()

    print(f"Wrote {args.out_header} ({n} sections, max pole radius = {max_pole:.6f})")
    print(f"  Max cascade boost : +{max_boost_db:.2f} dB -> pre-gain = {pre_gain_db:.2f} dB")
    print(f"  Residual 100Hz-10kHz: RMS = {rms_err:.2f} dB, Max = {max_err:.2f} dB")
    for i, s in enumerate(sections_param):
        print(f"    [{i}] f0={s['f0']:7.1f} Hz  Q={s['Q']:4.2f}  G={s['gain_db']:+6.2f} dB  (r={s['pole_radius']:.5f})")


if __name__ == "__main__":
    main()
